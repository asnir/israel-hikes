import {build} from 'esbuild';
import fs from 'node:fs/promises';
const result=await build({entryPoints:['worker/strength-client.ts'],bundle:true,platform:'browser',format:'esm',minify:true,write:false});
const text='// Generated by scripts/build-strength-client.mjs. Shared policy, no CDN.\nexport const strengthClient='+JSON.stringify(result.outputFiles[0].text)+';\n';
if(process.argv.includes('--check')){if(await fs.readFile('worker/strength-client.generated.ts','utf8')!==text)throw Error('Strength client artifact stale');}
else await fs.writeFile('worker/strength-client.generated.ts',text);
